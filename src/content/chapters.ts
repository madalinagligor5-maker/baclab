/** Grupurile de capitole, în ordinea primei apariții. */
export function chapterGroups(): { group: string; chapters: Chapter[] }[] {
  const out: { group: string; chapters: Chapter[] }[] = [];
  for (const ch of CHAPTERS_A) {
    let g = out.find((x) => x.group === ch.group);
    if (!g) {
      g = { group: ch.group, chapters: [] };
      out.push(g);
    }
    g.chapters.push(ch);
  }
  return out;
}
